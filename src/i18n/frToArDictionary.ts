/**
 * Translates any French or mixed French/Arabic UI phrase into clean Arabic.
 * Returns the original string untouched if no translation matches (e.g. user names, tracking codes, pure numbers).
 */
export function translatePhraseToArabic(raw: string): string {
  if (!raw) return raw;

  // Preserve leading and trailing whitespace so inline JSX fragments keep spacing intact
  const leadingMatch = raw.match(/^\s*/);
  const trailingMatch = raw.match(/\s*$/);
  const leading = leadingMatch ? leadingMatch[0] : '';
  const trailing = trailingMatch ? trailingMatch[0] : '';
  const trimmed = raw.trim();

  if (!trimmed) return raw;

  // Skip pure numbers, punctuation, emails, URLs, tracking codes (e.g. FAR-2026-..., RAM-2026-...)
  if (
    /^[\d\s.,:%+\-*/()•·✓✕⚠🚨🔄📦🛵🚗🚐🚲🏢🔗]+$/.test(trimmed) ||
    /^(FAR|RAM|BON|VRM|BL|BC|KP|TRK)-?[A-Z0-9-]+$/i.test(trimmed) ||
    /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(trimmed) ||
    /^https?:\/\//i.test(trimmed) ||
    /^\+?\d[\d\s\-()]{6,}$/.test(trimmed)
  ) {
    return raw;
  }

  const normalized = trimmed.replace(/\s+/g, ' ');
  const lower = normalized.toLowerCase();

  // 1. Exact lookup
  const exact = NORMALIZED_EXACT_MAP.get(lower);
  if (exact) return `${leading}${exact}${trailing}`;

  // 2. Fragment lookup
  const frag = FRAGMENT_MAP[lower];
  if (frag) return `${leading}${frag}${trailing}`;

  // 3. Trailing colon ":" or "*" or "..." normalization (preserve suffix cleanly)
  const suffixMatch = normalized.match(/^(.+?)\s*(:|\*|\.\.\.)$/);
  if (suffixMatch) {
    const baseLower = suffixMatch[1].trim().toLowerCase();
    const baseExact = NORMALIZED_EXACT_MAP.get(baseLower);
    if (baseExact) {
      const sep = suffixMatch[2] === ':' ? ' :' : suffixMatch[2] === '*' ? ' *' : '...';
      return `${leading}${baseExact}${sep}${trailing}`;
    }
  }

  // 4. Dynamic Patterns
  let m: RegExpMatchArray | null;

  // "Bonjour, ShopName"
  if ((m = normalized.match(/^Bonjour,\s*(.+)$/i))) {
    return `${leading}مرحباً، ${m[1]}${trailing}`;
  }

  // "Tous les statuts (2)", "Nouveaux (1)", "Tous (3)", "Tous mes colis (12)", "Voir tout (8)"
  if ((m = normalized.match(/^(.+?)\s*\((\d+)\)$/))) {
    const labelPart = m[1].trim().toLowerCase();
    const mappedLabel = NORMALIZED_EXACT_MAP.get(labelPart);
    if (mappedLabel) {
      return `${leading}${mappedLabel} (${m[2]})${trailing}`;
    }
  }

  // "Colis assignés à PartnerName"
  if ((m = normalized.match(/^Colis assignés à\s+(.+)$/i))) {
    return `${leading}الطرود المسندة إلى ${m[1]}${trailing}`;
  }

  // "Total versé : 1200 DH"
  if ((m = normalized.match(/^Total versé\s*:\s*(.+)$/i))) {
    return `${leading}إجمالي المدفوع : ${translatePhraseToArabic(m[1].trim())}${trailing}`;
  }

  // "30 DH / colis"
  if ((m = normalized.match(/^(\d+(?:[.,]\d+)?)\s*(?:DH|MAD)\s*\/\s*colis$/i))) {
    return `${leading}${m[1]} درهم / طرد${trailing}`;
  }

  // "30 DH livr. / 10 DH ret."
  if ((m = normalized.match(/^(\d+(?:[.,]\d+)?)\s*(?:DH|MAD)\s*livr\.\s*\/\s*(\d+(?:[.,]\d+)?)\s*(?:DH|MAD)\s*ret\.$/i))) {
    return `${leading}${m[1]} درهم توصيل / ${m[2]} درهم إرجاع${trailing}`;
  }

  // "5 livrés"
  if ((m = normalized.match(/^(\d+)\s+livrés?$/i))) {
    return `${leading}${m[1]} مسلّمة${trailing}`;
  }

  // "Modifier le Colis FAR-..."
  if ((m = normalized.match(/^Modifier le Colis\s+(.+)$/i))) {
    return `${leading}تعديل الطرد ${m[1]}${trailing}`;
  }

  // "Note: ..."
  if ((m = normalized.match(/^Note\s*:\s*(.+)$/i))) {
    return `${leading}ملاحظة : ${m[1]}${trailing}`;
  }

  // "25 colis" / "12 colis sélectionnés" / "8 colis · Date : 2026-10-27"
  if ((m = normalized.match(/^(\d+)\s+colis(?:\s*·\s*Date\s*:\s*(.+))?$/i))) {
    if (m[2]) {
      return `${leading}${m[1]} طرود · التاريخ : ${m[2]}${trailing}`;
    }
    return `${leading}${m[1]} طرد${trailing}`;
  }
  if ((m = normalized.match(/^(\d+)\s+colis sélectionnés?(.*)$/i))) {
    return `${leading}${m[1]} طرد محدد${m[2] ? ' ' + translatePhraseToArabic(m[2].trim()) : ''}${trailing}`;
  }

  // "Statut mis à jour vers X"
  if ((m = normalized.match(/^Statut mis à jour vers\s+(.+)$/i))) {
    const stAr = translatePhraseToArabic(m[1].trim());
    return `${leading}تم تحديث الحالة إلى ${stAr}${trailing}`;
  }

  // "Statut mis à jour par le livreur : X"
  if ((m = normalized.match(/^Statut mis à jour par le livreur\s*:\s*(.+)$/i))) {
    const stAr = translatePhraseToArabic(m[1].trim());
    return `${leading}تم تحديث الحالة من طرف الموزع : ${stAr}${trailing}`;
  }

  // "Colis affecté au livreur X" / "Affecté(s) à X"
  if ((m = normalized.match(/^(?:Colis )?[Aa]ffecté\(?s?\)?\s+(?:au livreur|à)\s+(.+)$/))) {
    return `${leading}تم تعيين الطرد للموزع ${m[1]}${trailing}`;
  }

  // "Total CRBT : X" / "Total : X" / "Ville : X" / "Responsable : X"
  if ((m = normalized.match(/^(Total(?:\s+CRBT|\s+COD)?(?:\s+filtré)?|Ville|Adresse|Client|Boutique|Livreur|Responsable|Téléphone|Statut|Date|Montant(?:\s+CRBT)?|Frais(?:\s+de\s+livraison)?|Net(?:\s+à\s+verser)?)\s*:\s*(.+)$/i))) {
    const keyAr = NORMALIZED_EXACT_MAP.get(m[1].trim().toLowerCase()) || m[1];
    const valAr = translatePhraseToArabic(m[2].trim());
    return `${leading}${keyAr} : ${valAr}${trailing}`;
  }

  // "Ex : ..." or "Ex: ..." -> replace prefix "Ex :" with "مثال :"
  if ((m = normalized.match(/^Ex\s*:\s*(.+)$/i))) {
    return `${leading}مثال : ${m[1]}${trailing}`;
  }

  // Currency replacement in standalone amounts: "150 MAD" / "150.00 DH"
  if ((m = normalized.match(/^([+\-]?\s*\d[\d\s.,]*)\s*(?:MAD|DH)$/i))) {
    return `${leading}${m[1].trim()} درهم${trailing}`;
  }

  // "N° suivi : ..." / "Colis X · WhatsApp..."
  if ((m = normalized.match(/^Colis\s+([A-Z0-9-]+)$/i))) {
    return `${leading}طرد ${m[1]}${trailing}`;
  }

  return raw;
}
